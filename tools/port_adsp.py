# Builds runtime/adsp/adsp21xx.cpp from MAME's adsp2100.cpp (reference/mame, tools/fetch_reference.sh):
# the constructor's register tables, reset, boot loading, IRQs (ADSP-2101 family), tables and the
# execution loop, with the device framework calls removed. Run again after updating the reference.
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, 'reference', 'mame', 'adsp2100.cpp')).read()

def between(start, end):
    a = src.index(start)
    b = src.index(end, a)
    return src[a:b]

def function(signature):
    """Body of a function from its signature line to the matching closing brace at column 0."""
    a = src.index(signature)
    b = src.index('\n}\n', a) + 3
    return src[a:b]

ctor = between('\t// create the tables\n', '\nadsp2100_device::adsp2100_device')
reset = function('void adsp21xx_device::device_reset()')
boot = function('void adsp21xx_device::load_boot_data(')
irq = function('bool adsp2101_device::generate_irq(int which, int indx)')
check = function('void adsp2101_device::check_irqs()')
tables = function('void adsp21xx_device::create_tables()')
setinput = function('void adsp21xx_device::execute_set_input(int inputnum, int state)')
run = function('void adsp21xx_device::execute_run()')

irq = irq.replace('adsp2101_device::', 'adsp21xx_device::')
check = check.replace('adsp2101_device::', 'adsp21xx_device::')
reset = reset.replace('void adsp21xx_device::device_reset()', 'void adsp21xx_device::reset()')
setinput = setinput.replace('execute_set_input(int inputnum, int state)', 'set_input_line(int inputnum, int state)')

# The execution loop: no halt line, no debugger; run a given number of cycles.
run = run.replace('void adsp21xx_device::execute_run()', 'int adsp21xx_device::run(int cycles)')
run = re.sub(r'\t// Return if CPU is halted\n\tif \(input_line_state\(INPUT_LINE_HALT\)\) \{.*?\n\t\}\n', '', run, flags=re.S)
run = run.replace('\tconst bool check_debugger = debugger_enabled();\n', '\tm_icount = cycles;\n')
run = re.sub(r'\t\tif \(check_debugger\)\n\t\t\tdebugger_instruction_hook\(m_pc\);\n', '', run)
run = re.sub(r'#if ADSP_TRACK_HOTSPOTS.*?#endif\n', '', run, flags=re.S)
assert run.rstrip().endswith('}')
run = run.rstrip()[:-1] + '\tint done = cycles - m_icount;\n\tm_total_cycles += done;\n\treturn done;\n}\n'

out = '''// license:BSD-3-Clause
// copyright-holders:Aaron Giles
//
// Generated by tools/port_adsp.py from MAME's src/devices/cpu/adsp2100/adsp2100.cpp: the ADSP-21xx
// core without the device framework (see adsp21xx.h). Do not edit by hand.
#include "adsp21xx.h"

#include <bit>
#include <cstdio>

namespace adsp {

namespace {
// As MAME's: on the argument's own type (the MAC overflow check takes bits 31-39 of a 64-bit value).
template <typename T> constexpr T BIT(T x, int n) { return (x >> n) & T(1); }
template <typename T> constexpr T BIT(T x, int n, int w) { return (x >> n) & ((T(1) << w) - 1); }
template <typename... A> void logerror(const char *fmt, A... a) { fprintf(stderr, fmt, a...); }
}

adsp21xx_device::adsp21xx_device(Bus *bus, uint32_t chiptype)
    : m_bus(bus), m_chip_type(chiptype),
      m_mstat_mask((chiptype >= CHIP_TYPE_ADSP2101) ? 0x7f : 0x0f),
      m_imask_mask((chiptype >= CHIP_TYPE_ADSP2181) ? 0x3ff : (chiptype >= CHIP_TYPE_ADSP2101) ? 0x3f : 0x0f)
{
\tmemset(&m_core, 0, sizeof(m_core));
\tmemset(&m_alt, 0, sizeof(m_alt));
\tmemset(&m_i, 0, sizeof(m_i));
\tmemset(&m_m, 0, sizeof(m_m));
\tmemset(&m_l, 0, sizeof(m_l));
\tmemset(&m_lmask, 0, sizeof(m_lmask));
\tmemset(&m_base, 0, sizeof(m_base));
\tmemset(&m_loop_stack, 0, sizeof(m_loop_stack));
\tmemset(&m_cntr_stack, 0, sizeof(m_cntr_stack));
\tmemset(&m_pc_stack, 0, sizeof(m_pc_stack));
\tmemset(&m_stat_stack, 0, sizeof(m_stat_stack));
\tmemset(&m_irq_state, 0, sizeof(m_irq_state));
\tmemset(&m_irq_latch, 0, sizeof(m_irq_latch));

''' + ctor.rstrip() + '\n\n' + boot + '\n' + reset + '\n#include "2100ops.hxx"\n\n' + irq + '\n' + check + '\n' + tables + '\n' + setinput + '\n' + run + '\n} // namespace adsp\n'

open(os.path.join(root, 'runtime', 'adsp', 'adsp21xx.cpp'), 'w').write(out)
print('wrote runtime/adsp/adsp21xx.cpp')
